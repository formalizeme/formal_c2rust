"""Why CompCert rejected a file, and which options an accepted one needed."""

from __future__ import annotations

import re
from pathlib import Path

from .benchmark import source_code

# Matched against the error text; first match wins. A group, if present, is
# appended to the label.
CATEGORIES = [
    (r"size of array is not a compile-time constant", "variable-length array"),
    (r"illegal arithmetic on a pointer to void", "arithmetic on void * (GNU)"),
    (r"invalid numerical constant '0[bB]", "binary literal (GNU, C23)"),
    (r"invalid numerical constant", "non-standard numeric literal"),
    (r"too large to be represented in a signed integer type", "integer literal too large for its type"),
    (r"_Atomic|stdatomic", "C11 atomics"),
    (r"_Thread_local|__thread", "thread-local storage"),
    (r"unknown builtin '(\w+)'", "GCC builtin"),
    (r"__u?int128", "128-bit integer (__int128)"),
    (r"fatal error: \w*intrin\.h", "x86 SIMD intrinsics"),
    (r"fatal error: (unity|check|cmocka|munit|greatest|utest|acutest|criterion/criterion|CUnit/\w+)\.h: No such",
     "external test framework"),
    (r"fatal error: \S+: No such file", "missing header"),
    (r"#error", "#error directive"),
    (r"long double", "long double"),
    (r"_Complex", "complex numbers"),
    (r"'(__)?asm(__)?'", "inline asm"),
    (r"timed out", "timeout"),
    (r"[Oo]ut of memory|Cannot allocate memory", "out of memory (refactor.memory_limit_mb)"),
    (r"syntax error after ':' and before '}'", "label at end of block (C23)"),
    (r"use of undeclared identifier '(\w+)'", "undeclared identifier"),
    (r"incomplete type '([^']+)'", "incomplete type"),
    (r"[Uu]nsupported|not supported", "unsupported feature"),
]

# For syntax errors: matched against the offending source line, followed by
# the bodies of any macros that line uses.
SYNTAX_PATTERNS = [
    (r"\bcase\b[^:]*\.\.\.", "case range (GNU)"),
    (r"\w\s*\(\s*\.\.\.\s*\)", "variadic function without a named parameter (C23)"),
    (r"(=|\))\s*\{\s*\}", "empty initializer {} (GNU, C23)"),
    (r"\b(__)?typeof(__)?\b", "typeof (GNU, C23)"),
    (r"\(\{", "statement expression (GNU)"),
    (r"^\s+(?!(?:else|if|while|for|switch|return|do)\b)[A-Za-z_][\w\s*]*?\b"
     r"(?!(?:if|while|for|switch)\b)\w+\s*\([^;]*\)\s*\{", "nested function (GNU)"),
]
_SYNTAX_AT = re.compile(r"^([^\s:]+):(\d+):(?:\d+:)? syntax error", re.M)
_DEFINE = re.compile(r"^\s*#\s*define\s+(\w+)(?:\([^)]*\))?[ \t]*(.*)$", re.M)
_IDENT = re.compile(r"\b[A-Za-z_]\w*\b")
_NOISE = re.compile(r"^(Fatal error; compilation aborted\.|\d+ errors? detected\.)$")
_SUGGESTED = re.compile(r"option \[(-f[\w-]+)\]")


def first_errors(output: str, limit: int = 3) -> str:
    """The first error lines (CompCert's syntax errors have no 'error:' prefix)."""
    errors = [line for line in output.splitlines()
              if "error" in line.lower() and not _NOISE.match(line.strip())]
    return "\n".join((errors or output.splitlines()[-limit:])[:limit])


def categorize(error: str, root: Path | None = None) -> str:
    """A short reason for a CompCert error. `root` is where the error's paths resolve."""
    missing = re.search(r"fatal error: (\S+): No such file", error)
    if missing and root and _make_target(root, missing.group(1)):
        return "header generated by the project's build"
    for pattern, label in CATEGORIES:
        m = re.search(pattern, error)
        if m:
            return f"{label} ({m.group(1)})" if m.groups() and m.group(1) else label
    if "syntax error" in error:
        line = _source_line(error, root)
        if line is not None:
            bodies = _macro_bodies(root)
            context = [line] + [bodies[w] for w in _IDENT.findall(line) if w in bodies]
            for pattern, label in SYNTAX_PATTERNS:
                if any(re.search(pattern, text) for text in context):
                    return label
        return "syntax CompCert does not accept"
    return "other"


def primary_error(errors: list[dict]) -> dict:
    """The failed attempt to report: the last one, unless it stopped in a system
    header and an earlier attempt got into the project's own code."""
    for attempt in reversed(errors):
        if not attempt["error"].startswith("/usr/"):
            return attempt
    return errors[-1]


def needed_options(units: list[dict]) -> list[str]:
    """The specific options behind accepted units' extra flags, as CompCert's
    errors from the earlier attempts name them."""
    needs: set[str] = set()
    for u in units:
        if not (u["accepted"] and u["flags"]):
            continue
        found = {o for att in u["errors"] for o in _SUGGESTED.findall(att["error"])}
        if any("'long double' type" in att["error"] for att in u["errors"]):
            found.add("-flongdouble")
        found |= {f for f in u["flags"] if f.startswith("-D")}
        needs |= found or set(u["flags"])
    return sorted(needs)


def _source_line(error: str, root: Path | None) -> str | None:
    m = _SYNTAX_AT.search(error)
    if not (m and root):
        return None
    try:
        return (root / m.group(1)).read_text(errors="replace").splitlines()[int(m.group(2)) - 1]
    except (OSError, IndexError):
        return None


def _make_target(root: Path, name: str) -> bool:
    """Whether a Makefile in the project has a rule that builds `name`."""
    rule = re.compile(rf"^{re.escape(name)}\s*:", re.M)
    return any(rule.search(f.read_text(errors="replace")) for f in root.rglob("*")
               if f.is_file() and (f.name in ("Makefile", "makefile", "GNUmakefile") or f.suffix == ".mk"))


def _macro_bodies(root: Path) -> dict[str, str]:
    bodies: dict[str, str] = {}
    for f in sorted(root.rglob("*")):
        if f.suffix in (".c", ".h") and f.is_file():
            for name, body in _DEFINE.findall(source_code(f).replace("\\\n", " ")):
                bodies.setdefault(name, body)
    return bodies
