def test_count_functions():
    assert count_functions("int f(int);\nint f(int $x)\n{\n  return $x;\n}\n\nvoid g(void)\n{\n}\n") == 2


def test_wrapper_defines_switches_and_includes_top_headers(tmp_path):
    (tmp_path / "lib.h").write_text('#ifndef LIB_H\n#define LIB_H\n#include "util.h"\n'
                                    "#ifdef LIB_IMPLEMENTATION\nint f(void) { return 1; }\n#endif\n#endif\n")
    (tmp_path / "util.h").write_text("#ifndef UTIL_IMPL_H\n#define UTIL_IMPL_H\nint g(void);\n#endif\n")
    path, top = write_wrapper(Project("lib", tmp_path, None))
    text = path.read_text()
    assert "#define LIB_IMPLEMENTATION" in text
    assert "UTIL_IMPL_H" not in text             # an include guard, not a switch
    assert '#include "lib.h"' in text and '#include "util.h"' not in text
    assert [h.name for h in top] == ["lib.h"]


def test_wrapper_ignores_includes_in_comments(tmp_path):
    (tmp_path / "lib.h").write_text('/* Usage:\n    #include "lib.h"\n*/\nint f(void) { return 1; }\n')
    path, _ = write_wrapper(Project("lib", tmp_path, None))
    assert '#include "lib.h"' in path.read_text()


def test_wrapper_keeps_static_functions(tmp_path):
    (tmp_path / "lib.h").write_text("static inline int twice(int x) { return 2 * x; }\n"
                                    "static int unused(void) { return 0; }\nint plain(void);\n")
    text = write_wrapper(Project("lib", tmp_path, None))[0].read_text()
    assert "(void (*)(void)) twice," in text and "(void (*)(void)) unused," in text
    assert "plain" not in text.split("c2r_keep")[1]   # only static definitions


