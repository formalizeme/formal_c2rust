@needs_ptridxgen
@needs_benchmark
def test_amp_is_partial_and_keeps_its_library_original(tmp_path):
    amp = project("amp")
    record = run_project(load_config(MAIN_CONFIG), amp)
    assert record.status == "partial"
    [lib] = [u for u in record.units if u.path == "src/amp.c"]
    assert not lib.accepted and lib.errors[-1]["category"] == "variable-length array"
    write_view(load_config(MAIN_CONFIG, [f"output.refactored_dir={tmp_path}"]), [record])
    view = sorted(str(p.relative_to(tmp_path / "amp")) for p in (tmp_path / "amp").rglob("*") if p.is_file())
    assert view == ["src/amp.c", "src/amp.h", "tests/test.light.c"]
    assert (tmp_path / "amp" / "src" / "amp.c").read_text() == (amp.c_dir / "src" / "amp.c").read_text()


@needs_ptridxgen
@needs_benchmark
def test_bigint_is_accepted_with_its_tests(tmp_path):
    record = run_project(load_config(MAIN_CONFIG), project("bigint"))
    assert record.accepted and record.header_only
    wrapper = record.units[0]
    assert wrapper.kind == "wrapper" and wrapper.out_path == "src/bigint.light.c"
    assert count_functions(wrapper.refactored) > 0
    assert {u.kind for u in record.units} == {"wrapper", "test"}
    assert all(u.clight and u.refactored and u.facts for u in record.units)   # in memory
    write_view(load_config(MAIN_CONFIG, [f"output.refactored_dir={tmp_path}"]), [record])
    view = sorted(str(p.relative_to(tmp_path / "bigint")) for p in (tmp_path / "bigint").rglob("*") if p.is_file())
    assert view == ["src/bigint.light.c", "tests/test1.light.c", "tests/test2.light.c", "tests/test3.light.c"]
    status = json.loads((tmp_path / "status.json").read_text())
    assert status["projects"]["bigint"]["accepted"]


