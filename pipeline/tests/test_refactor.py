def project(name):
    [p] = select(discover(REPO_ROOT / "CBench", REPO_ROOT / "RBench"), [name])
    return p


# --- diagnosis ---------------------------------------------------------------

@pytest.mark.parametrize("error, expected", [
    ("src/amp.c:82: error: size of array is not a compile-time constant", "variable-length array"),
    ("x.h:180: error: use of unknown builtin '__builtin_memcpy'", "GCC builtin (__builtin_memcpy)"),
    ("a.c:1:1: syntax error before '_Atomic'.", "C11 atomics"),
    ("b.c:27: error: illegal arithmetic on a pointer to void in binary '+'", "arithmetic on void * (GNU)"),
    ("u.c:13: error: invalid numerical constant '0b10000000'", "binary literal (GNU, C23)"),
    ("l.c:27:4: syntax error after ':' and before '}'.", "label at end of block (C23)"),
    ("m.c:11:12: fatal error: tibs.tsp.h: No such file or directory", "missing header"),
    ("/usr/include/linux/types.h:12:29: syntax error after '__int128' and before '__s128'.",
     "128-bit integer (__int128)"),
    ("src/aes.h:6:10: fatal error: immintrin.h: No such file or directory", "x86 SIMD intrinsics"),
    ("test/test.c:1:10: fatal error: unity.h: No such file or directory", "external test framework (unity)"),
    ("a.c:3: error: something new", "other"),
])
def test_categorize(error, expected):
    assert categorize(error) == expected


@pytest.mark.parametrize("line, expected", [
    ("  case 1 ... 8:", "case range (GNU)"),
    ("static void trace(...)", "variadic function without a named parameter (C23)"),
    ("  struct Env env = (struct Env){};", "empty initializer {} (GNU, C23)"),
    ("    int readIntFromHeader(char **header) {", "nested function (GNU)"),
    ("    else if (x) {", "syntax CompCert does not accept"),
    ("int ok = 1;", "syntax CompCert does not accept"),
])
def test_syntax_errors_are_categorized_by_source_line(tmp_path, line, expected):
    (tmp_path / "x.c").write_text(f"/* line 1 */\n{line}\n")
    assert categorize("x.c:2:5: syntax error after 'a' and before 'b'.", tmp_path) == expected


def test_syntax_error_inside_a_macro(tmp_path):
    (tmp_path / "x.h").write_text("#define SWAP(x,y) do { __typeof(x) _tmp = (x); (x) = (y); (y) = _tmp; } while(0)\n")
    (tmp_path / "x.c").write_text('#include "x.h"\n    if (a > b) { SWAP(a,b); }\n')
    assert categorize("x.c:2:34: syntax error after ')' and before '_tmp'.", tmp_path) == "typeof (GNU, C23)"


def test_generated_header_is_recognized(tmp_path):
    (tmp_path / "Makefile").write_text("tibs.tsp.h: $(TSP)\n\tgen > $@\n")
    error = "main.c:11:12: fatal error: tibs.tsp.h: No such file or directory"
    assert categorize(error, tmp_path) == "header generated by the project's build"
    assert categorize(error) == "missing header"


def test_primary_error_skips_system_header_failures():
    errors = [{"flags": [], "error": "src/a.c:3: error: own problem"},
              {"flags": ["-D_DEFAULT_SOURCE"], "error": "/usr/include/linux/types.h:12:29: syntax error"}]
    assert primary_error(errors)["error"].startswith("src/a.c")


def test_needed_options_come_from_compcert_suggestions():
    unit = {"accepted": True, "flags": ["-fall"], "errors": [
        {"flags": [], "error": "a.c:3: error: unsupported feature: passing struct by value "
                               "(consider adding option [-fstruct-passing])"}]}
    assert needed_options([unit]) == ["-fstruct-passing"]


